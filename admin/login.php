<?php
session_start();
require_once '../config/database.php';

// Check if already logged in
if (isset($_SESSION['admin_id'])) {
    redirect('dashboard.php');
}

$error = '';

if ($_SERVER['REQUEST_METHOD'] == 'POST') {
    $username = sanitize_input($_POST['username']);
    $password = $_POST['password'];
    
    if (empty($username) || empty($password)) {
        $error = 'Please enter both username and password.';
    } else {
        $db = Database::getInstance();
        $sql = "SELECT * FROM admin_login WHERE username = ? AND is_active = 1";
        $admin = $db->fetchOne($sql, [$username]);
        
        if ($admin && password_verify($password, $admin['password'])) {
            // Update last login
            $db->query("UPDATE admin_login SET last_login = NOW() WHERE id = ?", [$admin['id']]);
            
            // Set session
            $_SESSION['admin_id'] = $admin['id'];
            $_SESSION['admin_username'] = $admin['username'];
            $_SESSION['admin_name'] = $admin['full_name'];
            $_SESSION['admin_role'] = $admin['role'];
            $_SESSION['user_type'] = 'admin';
            
            display_message('Welcome back, ' . $admin['full_name'] . '!', 'success');
            redirect('dashboard.php');
        } else {
            $error = 'Invalid username or password.';
        }
    }
}
